// Writes src/generated.ts: the anatomy of every component in the preset's default config. Run it
// (`bun run generate`, or omni's `generate` task) after changing the preset; the drift test in
// src/anatomy.spec.ts fails until then.

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { pureform } from "@pureform/preset";

import { deriveAnatomies, renderAnatomyModule } from "../src/derive";

const HEADER = `// Generated by scripts/generate.ts from @pureform/preset's default components. Don't edit it;
// run the \`generate\` task after changing the preset.`;

const root = fileURLToPath(new URL("../../..", import.meta.url));
const target = "packages/anatomy/src/generated.ts";

writeFileSync(
    `${root}/${target}`,
    renderAnatomyModule(deriveAnatomies(pureform().components), {
        header: HEADER,
        typesFrom: "./types",
    }),
);
const formatted = spawnSync("bunx", ["oxfmt", target], {
    cwd: root,
    stdio: "inherit",
});
if (formatted.status !== 0) process.exit(formatted.status ?? 1);
console.log(`wrote ${target}`);
